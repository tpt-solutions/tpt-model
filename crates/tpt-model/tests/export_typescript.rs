//! TypeScript export: exact declarations for structs, enums and optional/collection types.

use serde::{Deserialize, Serialize};
use tpt_model::export::typescript;
use tpt_model::{EntityId, Model, Registry};

#[derive(Debug, Clone, Copy, Serialize, Deserialize, Model)]
#[tpt(version = 1, name = "Material")]
enum MaterialV1 {
    Steel,
    Alloy(u32),
}

#[derive(Debug, Serialize, Deserialize, Model)]
#[tpt(version = 1, name = "Part")]
struct PartV1 {
    id: EntityId,
    tags: Vec<String>,
    note: Option<String>,
    material: MaterialV1,
    dims: std::collections::BTreeMap<String, f64>,
}

#[test]
fn declarations_match_the_serde_json_shape() {
    let mut registry = Registry::new();
    registry.register::<MaterialV1>().unwrap();
    registry.register::<PartV1>().unwrap();
    let expected = [
        "// Generated by tpt-model. Do not edit.",
        "",
        "export type Material = \"Steel\" | { Alloy: number };",
        "",
        "export interface Part {",
        "  id: number[];",
        "  tags: string[];",
        "  note: string | null;",
        "  material: Material;",
        "  dims: Record<string, number>;",
        "}",
        "",
    ]
    .join("\n");
    assert_eq!(typescript(&registry), expected);
}
